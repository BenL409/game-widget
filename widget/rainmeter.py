"""Rainmeter output: renders the library into a variables file the skins @Include, then refreshes them."""

from __future__ import annotations

import configparser
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

from . import fmt
from .dusty import DustyGame
from .models import Game

SKIN_NAME = "GameWidget"  # root config folder under Rainmeter's Skins folder; also the skins' Group
MAX_ROWS = 8  # rows per section the skins can show
DEFAULT_RAINMETER_EXE = Path(r"C:\Program Files\Rainmeter\Rainmeter.exe")


def skins_dir() -> Path:
    """Rainmeter's Skins folder: SkinPath from %APPDATA%\\Rainmeter\\Rainmeter.ini, else Documents."""
    ini = Path(os.environ.get("APPDATA", "")) / "Rainmeter" / "Rainmeter.ini"
    if ini.is_file():
        raw = ini.read_bytes()
        text = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8", "replace")
        parser = configparser.ConfigParser(strict=False, interpolation=None)
        try:
            parser.read_string(text)
            path = parser.get("Rainmeter", "SkinPath", fallback="")
        except configparser.Error:
            path = ""
        if path:
            return Path(path)
    return Path.home() / "Documents" / "Rainmeter" / "Skins"


def data_path(skin_dir: str = "") -> Path:
    root = Path(skin_dir) if skin_dir else skins_dir() / SKIN_NAME
    return root / "@Resources" / "data.inc"


def _clean(text: str) -> str:
    # One line per value; '#' could be read as a Rainmeter #Variable# reference.
    return " ".join(str(text).split()).replace("#", "\uff03")


def _rows(prefix: str, rows: list[tuple[str, str, str, float]]) -> list[str]:
    lines = [f"{prefix}Count={len(rows)}", f"{prefix}None={0 if rows else 1}"]  # skins size themselves from these
    for i in range(1, MAX_ROWS + 1):
        name, value, sub, pct = rows[i - 1] if i <= len(rows) else ("", "", "", 0.0)
        lines += [
            f"{prefix}{i}Name={_clean(name)}",
            f"{prefix}{i}Value={_clean(value)}",
            f"{prefix}{i}Sub={_clean(sub)}",
            f"{prefix}{i}Pct={pct:.3f}",
            f"{prefix}{i}Hidden={0 if name else 1}",
        ]
    return lines


def render(games: list[Game], dusty: list[DustyGame], warnings: list[str], now: datetime | None = None) -> str:
    now = now or datetime.now(timezone.utc)
    recent = sorted((g for g in games if g.recent_minutes > 0), key=lambda g: -g.recent_minutes)[:MAX_ROWS]
    top = sorted((g for g in games if g.playtime_minutes > 0), key=lambda g: -g.playtime_minutes)[:MAX_ROWS]
    dusty = dusty[:MAX_ROWS]

    max_recent = max((g.recent_minutes for g in recent), default=1)
    max_top = max((g.playtime_minutes for g in top), default=1)
    max_idle = max((d.idle_days or 0 for d in dusty), default=0) or 1

    script = Path(__file__).resolve().parent.parent / "main.py"
    pythonw = Path(sys.executable).with_name("pythonw.exe")
    lines = [
        "; Generated by game-widget (widget/rainmeter.py). Overwritten on every refresh.",
        "[Variables]",
        f"Updated={datetime.now().strftime('%H:%M')}",
        f"GameCount={len(games)}",
        f"Status={_clean(warnings[0]) if warnings else ''}",
        f"StatusHidden={0 if warnings else 1}",
        f"PythonW={pythonw if pythonw.exists() else sys.executable}",
        f"MainPy={script}",
    ]
    lines += _rows("R", [(g.name, fmt.hours(g.recent_minutes), f"{fmt.hours(g.playtime_minutes)} total",
                          g.recent_minutes / max_recent) for g in recent])
    lines += _rows("M", [(g.name, fmt.hours(g.playtime_minutes), fmt.ago(g.last_played, now),
                          g.playtime_minutes / max_top) for g in top])
    lines += _rows("D", [(d.game.name, fmt.idle(d.idle_days) if d.idle_days is not None else "never",
                          fmt.size(d.game.size_bytes), (d.idle_days or 0) / max_idle) for d in dusty])
    return "\r\n".join(lines) + "\r\n"


def write(text: str, path: Path) -> None:
    """Atomic write as UTF-16 LE with BOM, the encoding Rainmeter reads non-ASCII text from reliably."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(text, encoding="utf-16", newline="")
    os.replace(tmp, path)


def _rainmeter_running() -> bool:
    import psutil

    return any((p.info.get("name") or "").lower() == "rainmeter.exe" for p in psutil.process_iter(["name"]))


def refresh_skins() -> None:
    """Ask a running Rainmeter to reload our skins. Never launches Rainmeter if it's closed."""
    if sys.platform != "win32" or not DEFAULT_RAINMETER_EXE.exists() or not _rainmeter_running():
        return
    subprocess.run([str(DEFAULT_RAINMETER_EXE), "!RefreshGroup", SKIN_NAME],
                   creationflags=subprocess.CREATE_NO_WINDOW, check=False, timeout=10)
