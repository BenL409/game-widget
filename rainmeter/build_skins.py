def _defaults() -> str:
    lines = []
    for prefix in "RMD":
        lines += [f"{prefix}Count=0", f"{prefix}None=1"]
        for i in range(1, MAX_ROWS + 1):
            lines += [f"{prefix}{i}Id=", f"{prefix}{i}Name=", f"{prefix}{i}Value=", f"{prefix}{i}Sub=",
                      f"{prefix}{i}Pct=0", f"{prefix}{i}Hidden=1"]
    return "\n".join(lines)


def section(name: str, **opts) -> str:
    style = opts.get("MeterStyle")
    if style and style != "sText":
        opts["MeterStyle"] = f"sText | {style}"
    body = "\n".join(f"{k}={v}" for k, v in opts.items() if v is not None)
    return f"[{name}]\n{body}\n"


