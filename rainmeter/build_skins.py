"""Generates the Rainmeter skin files (Rainmeter .ini has no loops, so the row blocks are written from here).

Run after editing:  python rainmeter/build_skins.py
Skin files must stay ASCII: Rainmeter reads .ini via the Windows API, which only handles ANSI or UTF-16.
Non-ASCII glyphs are written as Rainmeter character references, e.g. [\\x00B7].
Meter styles can't inherit from each other in Rainmeter, so meters list them all: MeterStyle=sText | sName.
"""

